// Builds dist/blackout-lab.html: the whole game in one file that opens straight
// from disk (double-click it), with no server and no install.
//
//     node tools/build.mjs           write dist/blackout-lab.html
//     node tools/build.mjs --check   fail if dist/blackout-lab.html is out of date
//
// The source files stay the place to make changes; this only stitches them
// together. Browsers refuse to load ES modules from file:// pages, so each module
// becomes a plain function scope in one <script>, in dependency order, under a
// banner naming the file it came from. Nothing is minified, so the result can
// still be read and, at a pinch, edited by hand.
//
// Only the module syntax the game uses is supported: `import { a, b } from './x.js'`
// and `export const|let|function|class name`. Anything else stops the build.

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'dist', 'blackout-lab.html');

const IMPORT = /^import\s*\{([^}]*)\}\s*from\s*'(\.[^']+)';?\s*$/gm;
const EXPORT = /^export\s+(?:async\s+)?(const|let|function\*?|class)\s+([A-Za-z_$][\w$]*)/gm;

const rel = (path) => relative(ROOT, path).split('\\').join('/');

function fail(message) {
  console.error(`build failed: ${message}`);
  process.exit(1);
}

function scopeName(path) {
  return `module_${rel(path).replace(/\.js$/, '').replace(/[^A-Za-z0-9]+/g, '_')}`;
}

// Every module reachable from `entry`, dependencies first.
function collect(entry) {
  const order = [];
  const seen = new Map(); // path -> 'busy' | 'done'
  function visit(path) {
    if (seen.get(path) === 'done') return;
    if (seen.get(path) === 'busy') fail(`circular import through ${rel(path)}`);
    seen.set(path, 'busy');
    const source = readFileSync(path, 'utf8');
    const imports = [...source.matchAll(IMPORT)].map((m) => ({
      names: m[1].split(',').map((s) => s.trim()).filter(Boolean),
      path: resolve(dirname(path), m[2]),
    }));
    const left = source.replace(IMPORT, '');
    if (/^\s*import\b/m.test(left) || /\bimport\s*\(/.test(left)) fail(`${rel(path)}: only "import { ... } from './file.js'" is supported`);
    if (/^\s*export\s+(default|\{|\*)/m.test(left)) fail(`${rel(path)}: only "export const|let|function|class name" is supported`);
    for (const dep of imports) visit(dep.path);
    order.push({ path, source: left, imports, exports: [...left.matchAll(EXPORT)].map((m) => m[2]) });
    seen.set(path, 'done');
  }
  visit(entry);
  return order;
}

function bundle(modules) {
  const byPath = new Map(modules.map((m) => [m.path, m]));
  return modules
    .map((m) => {
      const uses = m.imports.map((dep) => {
        const from = byPath.get(dep.path);
        for (const name of dep.names) {
          if (!from.exports.includes(name)) fail(`${rel(m.path)} imports ${name}, which ${rel(dep.path)} does not export`);
        }
        return `const { ${dep.names.join(', ')} } = ${scopeName(dep.path)};\n`;
      });
      const body = m.source.replace(/^export\s+/gm, '').replace(/^\n+/, '').trimEnd();
      const banner = `// ${'='.repeat(76)}\n// ${rel(m.path)}\n// ${'='.repeat(76)}`;
      return `${banner}\nconst ${scopeName(m.path)} = (() => {\n${uses.join('')}${uses.length ? '\n' : ''}${body}\n\nreturn {${m.exports.length ? ` ${m.exports.join(', ')} ` : ''}};\n})();\n`;
    })
    .join('\n');
}

function build() {
  const page = readFileSync(join(ROOT, 'index.html'), 'utf8');
  const css = readFileSync(join(ROOT, 'main.css'), 'utf8').trimEnd();
  const modules = collect(join(ROOT, 'main.js'));
  const contents = modules.map((m) => `//   ${rel(m.path)}`).join('\n');
  const script = `// Blackout Lab, single-file build. Generated by tools/build.mjs: do not edit by
// hand unless you have to. Change the source files and run \`node tools/build.mjs\`.
//
// Sections, in order (each one is a source file, in its own scope):
${contents}
${bundle(modules)}`;
  if (/<\/script|<!--/i.test(script)) fail('the code contains "</script" or "<!--", which would end the inline <script> early');

  const link = /^<link rel="stylesheet" href="main\.css">\n/m;
  const entry = /^<script type="module" src="main\.js"><\/script>\n/m;
  if (!link.test(page) || !entry.test(page)) fail('index.html no longer links main.css and main.js the way this script expects');
  const style = `<style>\n/* ${'='.repeat(74)}\n   main.css\n   ${'='.repeat(74)} */\n${css}\n</style>\n`;
  // The content security policy lets exactly this inline script run, by its hash.
  const body = `\n${script}`;
  const hash = createHash('sha256').update(body).digest('base64');
  const csp = /script-src 'self'/;
  if (!csp.test(page)) fail("index.html's content security policy no longer has script-src 'self'");
  // A classic script at the end of <body>, so the page exists before it runs (as a module would).
  return page
    .replace(csp, () => `script-src 'sha256-${hash}'`)
    .replace(link, () => style)
    .replace(entry, '')
    .replace(/<\/body>/, () => `<script>${body}</script>\n</body>`);
}

const html = build();
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch (err) {
    // missing counts as out of date
  }
  if (current !== html) fail(`${rel(OUT)} is out of date: run "node tools/build.mjs"`);
  console.log(`${rel(OUT)} is up to date`);
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, html);
  console.log(`wrote ${rel(OUT)} (${Math.round(html.length / 1024)} KB)`);
}
